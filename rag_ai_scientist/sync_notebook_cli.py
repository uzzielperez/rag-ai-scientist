"""Keep the DALI flow notebook in step with `dali_onboard.py`.

`dali-notebook-sync` answers one question in CI or locally: *does the
generated SWAN notebook still describe the flow code as it is now?*

  dali-notebook-sync status  [--repo DIR] [--out DIR]
  dali-notebook-sync check   # exit 1 if stale / hand-edited / missing
  dali-notebook-sync sync    # regenerate when stale (no --force needed)
  dali-notebook-sync push    # sync, then copy the .ipynb to a SWAN project

`push` needs the SWAN side to be reachable from where you run it. Two ways:

  1. Jupyter Hub REST (a JupyterHub token with access to your SWAN server):
       export SWAN_URL=https://swan.cern.ch/user/<cern-username>
       export SWAN_TOKEN=<hub token>
       dali-notebook-sync push --swan-dir dali-notebook
  2. Shared filesystem (AFS / EOS mounted where you run this):
       dali-notebook-sync push --target /eos/user/<i>/<u>/dali-notebook

The notebook is generated, so sync direction is always code -> notebook. If a
notebook has been hand-edited, `status` says so and `sync` refuses without
`--force`: edit `dali_onboard.py` (or add a section with `--append-markdown`)
instead of the notebook.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

from rag_ai_scientist.sync_notebook import (
    MANIFEST_NAME,
    NOTEBOOK_NAME,
    _sha256,
    build_notebook,
    find_source,
    manifest_path,
    write_notebook,
)

STATE_GENERATED = "generated"
STATE_STALE = "stale (dali_onboard.py changed since generation)"
STATE_HAND_EDITED = "hand-edited (differs from the last generated copy)"
STATE_MISSING = "missing"
STATE_UNKNOWN = "present, but no manifest - generated by an older tool?"


def _paths(repo: Path, out: str) -> tuple[Path, Path, Path]:
    out_dir = Path(out).resolve() if out else repo / "docs" / "notebook"
    return out_dir, out_dir / NOTEBOOK_NAME, manifest_path(out_dir)


def status(repo: Path, out: str = "") -> dict:
    out_dir, nb_path, man_path = _paths(repo, out)
    source = find_source(repo)
    report = {"source": str(source), "source_sha256": _sha256(source),
              "notebook": str(nb_path), "out_dir": str(out_dir)}
    if not nb_path.exists():
        report.update(state=STATE_MISSING, up_to_date=False)
        return report
    if not man_path.exists():
        report.update(state=STATE_UNKNOWN, up_to_date=False,
                      notebook_sha256=_sha256(nb_path))
        return report
    manifest = json.loads(man_path.read_text(encoding="utf-8"))
    stored_nb = manifest.get("notebook_sha256", "")
    stored_src = manifest.get("source_sha256", "")
    report["manifest"] = {k: manifest.get(k) for k in
                          ("generated_utc", "source_sha256", "git", "tool")}
    report["notebook_sha256"] = _sha256(nb_path)
    if stored_nb and stored_nb != report["notebook_sha256"]:
        report.update(state=STATE_HAND_EDITED, up_to_date=False)
    elif stored_src != report["source_sha256"]:
        report.update(state=STATE_STALE, up_to_date=False)
    else:
        report.update(state=STATE_GENERATED, up_to_date=True)
    return report


def do_sync(repo: Path, out: str, force: bool, quiet: bool) -> dict:
    out_dir, nb_path, _ = _paths(repo, out)
    source = find_source(repo)
    report = status(repo, out)
    if report["up_to_date"]:
        if not quiet:
            print(f"up to date: {nb_path}")
        return report
    if report["state"] == STATE_HAND_EDITED and not force:
        raise SystemExit(
            f"{nb_path} was hand-edited since it was generated.\n"
            "The notebook is generated output: change dali_onboard.py, or pass "
            "--force to overwrite the edits.")
    nb = build_notebook(source)
    path = write_notebook(nb, out_dir, source)
    if not quiet:
        print(f"regenerated {path} from {source} "
              f"(sha256 {nb.metadata['dali']['source_sha256'][:12]})")
    return status(repo, out)


def _jupyter_request(base: str, token: str, api_path: str, method: str = "GET",
                     payload: bytes | None = None, content_type: str = ""):
    url = urllib.parse.urljoin(base.rstrip("/") + "/", api_path.lstrip("/"))
    req = urllib.request.Request(url, data=payload, method=method)
    req.add_header("Authorization", f"token {token}")
    if content_type:
        req.add_header("Content-Type", content_type)
    return urllib.request.urlopen(req, timeout=120)


def push_to_jupyterhub(nb_path: Path, swan_dir: str, swan_url: str,
                       token: str, quiet: bool = False) -> None:
    """Upload the notebook into a directory of a running JupyterHub (SWAN) server."""
    api = urllib.parse.quote(swan_dir.strip("/"), safe="/")
    name = urllib.parse.quote(nb_path.name)
    url = f"{swan_url.rstrip('/')}/api/contents/{api}/{name}" if api else \
          f"{swan_url.rstrip('/')}/api/contents/{name}"
    body = json.dumps({
        "type": "notebook",
        "format": "json",
        "content": json.loads(nb_path.read_text(encoding="utf-8")),
    }).encode("utf-8")
    req = urllib.request.Request(url, data=body, method="PUT")
    req.add_header("Authorization", f"token {token}")
    req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, timeout=180) as resp:
            if not quiet:
                print(f"uploaded {nb_path.name} -> {url} (HTTP {resp.status})")
    except urllib.error.HTTPError as exc:
        hint = ""
        if exc.code in (403, 404):
            hint = ("\n  403/404 usually means the SWAN server is not running, the "
                    "token is for another host, or the directory does not exist yet.\n"
                    "  Start the session at https://swan.cern.ch first, or create the "
                    "directory in the SWAN file browser and retry.")
        raise SystemExit(f"SWAN upload failed: HTTP {exc.code} {exc.reason}.{hint}")


def push_to_target(nb_path: Path, target: Path, quiet: bool = False) -> None:
    target.mkdir(parents=True, exist_ok=True)
    dest = target / nb_path.name
    shutil.copy2(nb_path, dest)
    manifest = manifest_path(nb_path.parent)
    if manifest.exists():
        shutil.copy2(manifest, target / manifest.name)
    if not quiet:
        print(f"copied {nb_path.name} -> {dest}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="dali-notebook-sync",
        description="Check / refresh / deliver the generated DALI flow notebook.")
    parser.add_argument("command", nargs="?", default="status",
                        choices=["status", "check", "sync", "push"])
    parser.add_argument("--repo", default=".", help="rag-ai-scientist checkout.")
    parser.add_argument("--out", default="", help="Notebook dir (default <repo>/docs/notebook).")
    parser.add_argument("--force", action="store_true",
                        help="Overwrite a hand-edited notebook.")
    parser.add_argument("--quiet", action="store_true")
    parser.add_argument("--json", action="store_true", help="Machine-readable status.")
    parser.add_argument("--target", default="",
                        help="push: filesystem dir (AFS/EOS) to copy the .ipynb into.")
    parser.add_argument("--swan-dir", default="",
                        help="push: directory inside your SWAN session to upload into.")
    parser.add_argument("--swan-url", default=os.environ.get("SWAN_URL", ""),
                        help="push: SWAN/JupyterHub base URL (or $SWAN_URL).")
    parser.add_argument("--swan-token", default=os.environ.get("SWAN_TOKEN", ""),
                        help="push: JupyterHub API token (or $SWAN_TOKEN).")
    args = parser.parse_args(argv)

    repo = Path(args.repo).resolve()
    out_dir, nb_path, _ = _paths(repo, args.out)

    if args.command == "status":
        report = status(repo, args.out)
        if args.json:
            print(json.dumps(report, indent=2))
        else:
            for key in ("notebook", "state", "up_to_date", "source",
                        "source_sha256", "notebook_sha256"):
                if key in report:
                    print(f"{key:>18}: {report[key]}")
            man = report.get("manifest") or {}
            if man:
                git = man.get("git") or {}
                print(f"{'generated':>18}: {man.get('generated_utc')} "
                      f"(commit {git.get('commit', '?')}{' dirty' if git.get('dirty') else ''}, "
                      f"{git.get('branch', '?')})")
            if not report["up_to_date"]:
                print("\nnext: dali-notebook-sync sync --repo <checkout>")
        return 0 if report["up_to_date"] else (0 if args.command == "status" else 1)

    if args.command == "check":
        report = status(repo, args.out)
        print(f"{report['state']}  ({nb_path})")
        if report["up_to_date"]:
            return 0
        print("fix: dali-notebook-sync sync --repo <checkout>   "
              "(then commit the .ipynb)")
        return 1

    if args.command == "sync":
        do_sync(repo, args.out, args.force, args.quiet)
        return 0

    # push
    if not nb_path.exists():
        do_sync(repo, args.out, args.force, args.quiet)
    if args.target:
        push_to_target(nb_path, Path(args.target).expanduser().resolve(), args.quiet)
        print(f"Open it in SWAN: your project -> {args.target}/{nb_path.name}")
        return 0
    if args.swan_dir and args.swan_url and args.swan_token:
        push_to_jupyterhub(nb_path, args.swan_dir, args.swan_url, args.swan_token,
                           args.quiet)
        return 0
    raise SystemExit(
        "push needs either\n"
        "  --target /path/on/shared/fs        (AFS or EOS mount)\n"
        "or\n"
        "  --swan-dir DIR --swan-url https://swan.cern.ch/user/<user> "
        "--swan-token <hub token>\n"
        "The token comes from your JupyterHub token page; the SWAN session must "
        "be running.")


if __name__ == "__main__":
    raise SystemExit(main())
